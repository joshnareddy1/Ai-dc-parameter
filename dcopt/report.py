"""Create a single index report from the completed project stages."""
from __future__ import annotations

import argparse
from pathlib import Path

from dcopt.config import load_config


def run(config_path: str | Path) -> Path:
    config_path = Path(config_path).resolve()
    config = load_config(config_path)
    results_dir = Path(config["paths"]["results_dir"])
    if not results_dir.is_absolute():
        results_dir = config_path.parent / results_dir
    results_dir.mkdir(parents=True, exist_ok=True)

    stages = [
        ("Phase 0 – Data foundation", "phase0_data_foundation/summary.md"),
        ("Baseline", "01_baseline/summary.md"),
        ("Measurement settling", "02_settling/summary.md"),
        ("Static reduction", "03_static/summary.md"),
        ("Test ordering", "04_ordering/summary.md"),
        ("Predictive testing", "05_predictive/summary.md"),
        ("Adaptive testing", "06_adaptive/summary.md"),
        ("PAT", "07_pat/summary.md"),
        ("Combined scorecard", "08_scorecard/summary.md"),
        ("Monitoring", "09_monitoring/summary.md"),
        ("Synthetic DPPM safety demonstration", "10_synthetic_dppm/summary.md"),
    ]
    lines = ["# DC Parametric Test-Time Optimization – Project Report", "",
             "This report consolidates the outputs generated by `run_all.py`.",
             "Synthetic-data results are for methodology validation only; they are not production qualification.", ""]
    for title, relative in stages:
        path = results_dir / relative
        lines.extend([f"## {title}", ""])
        if path.exists():
            lines.extend([path.read_text(encoding="utf-8").strip(), ""])
        else:
            lines.extend([f"Not generated: `{relative}`", ""])
    output = results_dir / "PROJECT_REPORT.md"
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Project report written to {output}")
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config.yaml")
    args = parser.parse_args()
    run(args.config)


if __name__ == "__main__":
    main()
